export function isEnglish(subject) {
  return String(subject || '').trim().toLowerCase() === 'english';
}

// 选系统提示词。mode:'reading' 是教材阅读辅导，与学科无关，单独一条。
export function systemPrompt({ subject, ask, concept, reading }) {
  if (ask) {
    if (reading) return READ_ASK;
    return isEnglish(subject) ? EN_ASK : GEN_ASK;
  }
  if (concept) return isEnglish(subject) ? EN_CONCEPT : GEN_CONCEPT;
  return isEnglish(subject) ? EN_EXPLAIN : GEN_EXPLAIN;
}
